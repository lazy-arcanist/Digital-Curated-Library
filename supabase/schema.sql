-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text not null,
  created_at  timestamptz not null default now()
);

create table if not exists public.types (
  id          bigint generated by default as identity primary key,
  name        text not null,
  created_at  timestamptz not null default now()
);

create table if not exists public.resources (
  id           bigint generated by default as identity primary key,
  name         text not null,
  description  text,
  -- A category cannot be deleted while resources still use it.
  category_id  bigint references public.categories (id) on delete restrict,
  -- Legacy single type / single URL, kept in sync with types[1] / links[1] by the app.
  type         text,
  url          text not null default '',
  -- Current columns used by the app.
  types        text[] not null default '{}',
  tags         text[] not null default '{}',
  links        jsonb  not null default '[]'::jsonb,
  is_bookmarked boolean not null default false,
  created_at   timestamptz not null default now(),
  -- Set by the app on edits. Do NOT add an auto-update trigger: bookmarking must not change it.
  updated_at   timestamptz not null default now()
);

-- Names are unique, ignoring upper/lower case.
create unique index if not exists categories_name_unique on public.categories (lower(name));
create unique index if not exists types_name_unique on public.types (lower(name));

create index if not exists resources_category_id_idx on public.resources (category_id);

-- ---------------------------------------------------------------------------
-- Optional: exact database size for the admin storage card
-- ---------------------------------------------------------------------------

create or replace function public.get_database_size()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$ select pg_catalog.pg_database_size(pg_catalog.current_database()); $$;

grant execute on function public.get_database_size() to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
-- WARNING: the app has no real login. The admin password is checked in the browser only,
-- so the policies below let anyone holding the public key read AND write these tables.
-- That is what makes the admin page work, but it is not secure for a public site.
-- See the README notes on hardening before sharing the deployed app widely.

alter table public.categories enable row level security;
alter table public.types      enable row level security;
alter table public.resources  enable row level security;

drop policy if exists "categories_all" on public.categories;
create policy "categories_all" on public.categories
  for all to anon, authenticated using (true) with check (true);

drop policy if exists "types_all" on public.types;
create policy "types_all" on public.types
  for all to anon, authenticated using (true) with check (true);

drop policy if exists "resources_all" on public.resources;
create policy "resources_all" on public.resources
  for all to anon, authenticated using (true) with check (true);

